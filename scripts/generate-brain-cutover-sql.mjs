/**
 * Generates the destructive Brain-cutover SQL: the `DROP TABLE` statements for
 * every owner-private Brain table, derived authoritatively from
 * `@uwe/product-contracts` (BRAIN_MODEL_NAMES) × the schema's `@@map` names, so
 * it never drifts from the contracts.
 *
 * This is Runbook stage 9 (docs/engineering/brain-migration-runbook.md). It is
 * the LAST step of the physical migration and is NOT applied by this script — it
 * only writes the SQL file. Applying it to `uwe.db` is coherent ONLY after all
 * Brain services have been repointed to a separate `uwe-brain.db` (stages 3–8);
 * running it before that deletes Brain instead of moving it and breaks every
 * Brain feature.
 *
 * Run: `node scripts/generate-brain-cutover-sql.mjs`
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BRAIN_MODEL_NAMES } from "../packages/product-contracts/src/prisma-model-boundaries.ts";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const schema = fs.readFileSync(path.join(root, "packages/database/prisma/schema.prisma"), "utf8");

const tableOf = {};
const modelRe = /model\s+([A-Za-z0-9_]+)\s*\{([\s\S]*?)\n\}/g;
let match;
while ((match = modelRe.exec(schema)) !== null) {
  const mapped = match[2].match(/@@map\("([^"]+)"\)/);
  tableOf[match[1]] = mapped ? mapped[1] : match[1];
}

const tables = BRAIN_MODEL_NAMES.map((name) => tableOf[String(name)]);
if (tables.some((t) => !t)) {
  console.error("Could not resolve a table name for every Brain model — aborting.");
  process.exit(1);
}

const header = `-- AUTO-GENERATED by scripts/generate-brain-cutover-sql.mjs — do not edit by hand.
-- Brain cutover: DROP the ${tables.length} owner-private Brain tables from uwe.db.
--
-- !!! DESTRUCTIVE — Runbook stage 9 (docs/engineering/brain-migration-runbook.md) !!!
-- Apply ONLY after stages 3-8: a separate uwe-brain.db exists, every Brain
-- service is repointed to it, and integrity/restore/dry-run are green. Running
-- this before repointing DELETES Brain (it does not move it) and breaks all
-- Brain features. Take a verified backup of uwe.db first.
--
-- Apply (only when the above holds):
--   sqlite3 /var/lib/uwe/uwe.db < deploy/migrations/brain-cutover-drop.sql
`;

const body = [
  "",
  "PRAGMA foreign_keys = OFF;",
  "BEGIN TRANSACTION;",
  "",
  ...tables.map((t) => `DROP TABLE IF EXISTS "${t}";`),
  "",
  "COMMIT;",
  "PRAGMA foreign_keys = ON;",
  "",
].join("\n");

const outPath = path.join(root, "deploy/migrations/brain-cutover-drop.sql");
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, `${header}${body}`);
console.log(`Wrote ${path.relative(root, outPath)} (${tables.length} tables).`);
